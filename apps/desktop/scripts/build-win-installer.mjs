import { execFileSync } from 'node:child_process';
import { existsSync, statSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const desktopRoot = resolve(__dirname, '..');
const releaseDir = resolve(desktopRoot, 'release');
const unpackedDir = resolve(releaseDir, 'win-unpacked');
const setupExePath = resolve(releaseDir, 'pMusic-Setup-0.2.0.exe');
const nsiScriptPath = resolve(releaseDir, 'pmusic-installer.nsi');

// 1. Build win-unpacked and zip via electron-builder
execFileSync(
  'npx',
  [
    'electron-builder',
    '--win',
    'zip',
    '--config',
    'electron-builder.yml',
    '-c.win.signAndEditExecutable=false',
    '-c.npmRebuild=false',
  ],
  { cwd: desktopRoot, stdio: 'inherit' }
);

if (!existsSync(resolve(unpackedDir, 'pmusic.exe'))) {
  throw new Error('win-unpacked/pmusic.exe was not generated by electron-builder');
}

// 2. Compile full standalone Windows Setup .exe using native Linux /usr/bin/makensis
const nsiScript = `!include "MUI2.nsh"

Name "pMusic"
OutFile "${setupExePath}"
InstallDir "$LOCALAPPDATA\\Programs\\pMusic"
RequestExecutionLevel user
SetCompressor /SOLID lzma
SetCompressorDictSize 32

!define MUI_ABORTWARNING
!define MUI_FINISHPAGE_RUN "$INSTDIR\\pmusic.exe"
!define MUI_FINISHPAGE_RUN_TEXT "Iniciar pMusic ahora"

!insertmacro MUI_PAGE_WELCOME
!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_PAGE_FINISH

!insertmacro MUI_UNPAGE_CONFIRM
!insertmacro MUI_UNPAGE_INSTFILES

!insertmacro MUI_LANGUAGE "Spanish"

Section "pMusic Application" SecMain
  SetOutPath "$INSTDIR"
  File /r "${unpackedDir}\\*.*"

  WriteUninstaller "$INSTDIR\\Uninstall-pMusic.exe"
  CreateShortCut "$DESKTOP\\pMusic.lnk" "$INSTDIR\\pmusic.exe"
  CreateDirectory "$SMPROGRAMS\\pMusic"
  CreateShortCut "$SMPROGRAMS\\pMusic\\pMusic.lnk" "$INSTDIR\\pmusic.exe"
  CreateShortCut "$SMPROGRAMS\\pMusic\\Desinstalar pMusic.lnk" "$INSTDIR\\Uninstall-pMusic.exe"
SectionEnd

Section "Uninstall"
  Delete "$DESKTOP\\pMusic.lnk"
  RMDir /r "$SMPROGRAMS\\pMusic"
  RMDir /r "$INSTDIR"
SectionEnd
`;

writeFileSync(nsiScriptPath, nsiScript, 'utf-8');
execFileSync('/usr/bin/makensis', ['-V2', nsiScriptPath], { stdio: 'inherit' });

const st = statSync(setupExePath);
console.log(`Built full self-contained Windows Setup installer: ${setupExePath} (${(st.size / 1024 / 1024).toFixed(2)} MB)`);
